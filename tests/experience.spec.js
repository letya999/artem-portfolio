import {test,expect} from '@playwright/test';
test('career sculptures sit left of the text, survive toggles and resize, and return to the portrait',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>{window.scenes=[];window.__THREE_DEVTOOLS__=new EventTarget();window.__THREE_DEVTOOLS__.addEventListener('observe',({detail})=>{if(detail.isScene)window.scenes.push(detail);});});
 await page.setViewportSize({width:1440,height:900});await page.goto('/ru');
 await expect(page.locator('.portrait-stage')).toHaveClass(/loaded/,{timeout:20000});
 await expect(page.locator('#experience details[open]')).toHaveCount(0);
 await expect(page.locator('#experience .company')).toHaveText(['Twinby','Финтех-холдинг','МТС','ЮMoney','Itis Team','Renewal Studio']);
 await page.locator('#experience summary').first().click();
 await expect(page.locator('.job-results').first()).toBeVisible();
 await expect.poll(()=>page.evaluate(()=>window.scenes.flatMap(s=>s.children).find(m=>m.userData.dollOpen)?.userData.dollOpen.value[0])).toBeGreaterThan(.95);
 const layout=await page.locator('.career-entry').first().evaluate(e=>({slot:e.querySelector('.matryoshka-slot').getBoundingClientRect().right,text:e.querySelector('details').getBoundingClientRect().left,card:e.querySelector('details').getBoundingClientRect().width,total:e.getBoundingClientRect().width}));
 expect(layout.slot).toBeLessThan(layout.text);
 expect(layout.text-layout.slot).toBeLessThanOrEqual(24);expect(layout.card/layout.total).toBeGreaterThan(.75);
 await page.locator('#experience summary').first().click();
 await expect.poll(()=>page.evaluate(()=>window.scenes.flatMap(s=>s.children).find(m=>m.userData.dollOpen)?.userData.dollOpen.value[0])).toBeLessThan(.05);
 await page.setViewportSize({width:390,height:844});
 await page.locator('#experience summary').first().scrollIntoViewIfNeeded();
 await expect(page.locator('.portrait-stage')).toHaveAttribute('data-scene','experience');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
 await expect(page.locator('.portrait-stage')).toHaveAttribute('data-scene','portrait');
 const restored=await page.locator('.portrait-stage').evaluate(e=>{const a=e.getBoundingClientRect(),b=e.querySelector('canvas').getBoundingClientRect();return {left:Math.abs(a.left-b.left),width:Math.abs(a.width-b.width)};});
 expect(restored.left).toBeLessThan(1);expect(restored.width).toBeLessThan(1);expect(errors).toEqual([]);
});
