import {test,expect} from '@playwright/test';
test.use({locale:'en-US'});
test('complete locale selection, persistence, browser detection, navigation and removed controls',async({page})=>{
 await page.goto('/');
 await expect.soft(page.locator('.portrait-controls button')).toHaveCount(0);
 expect.soft(await page.locator('header').evaluate(e=>getComputedStyle(e).position)).toBe('sticky');
 await expect.soft(page.locator('html')).toHaveAttribute('lang','en');
 await expect.soft(page.locator('#experience h2')).toHaveText('Work experience');
 await expect.soft(page).toHaveTitle(/Artem/);
 expect.soft(await page.locator('meta[name="description"]').getAttribute('content')).toContain('7+ years');
 await page.evaluate(()=>{const s=document.querySelector('select');if(s){s.value='kk';s.dispatchEvent(new Event('change',{bubbles:true}));}});
 await page.waitForURL('**/kk.html');await expect.soft(page.locator('html')).toHaveAttribute('lang','kk');
 expect.soft(await page.evaluate(()=>localStorage.getItem('portfolio-language'))).toBe('kk');
 await page.reload();await expect.soft(page.locator('html')).toHaveAttribute('lang','kk');
 await expect.soft(page.locator('#experience h2')).toHaveText('Жұмыс тәжірибесі');
 await page.evaluate(()=>{const s=document.querySelector('select');if(s){s.value='en';s.dispatchEvent(new Event('change',{bubbles:true}));}});
 await page.waitForURL('**/en.html');
 await page.locator('.practice-more').last().click();
 await expect.soft(page.locator('#practice dialog > div:not([hidden])')).toContainText('Project examples');await page.keyboard.press('Escape');
 await page.locator('header a[href="#experience"]').click();await page.waitForTimeout(1200);
 expect.soft(await page.locator('#experience').evaluate(e=>e.getBoundingClientRect().top)).toBeGreaterThan(60);
 await page.setViewportSize({width:390,height:844});
 expect.soft(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
